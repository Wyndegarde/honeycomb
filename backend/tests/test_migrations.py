from collections.abc import AsyncIterator
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import text
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import AsyncEngine

from app.db.db_engine import get_engine

ALEMBIC_INI = Path(__file__).parent.parent / "app" / "db" / "alembic.ini"
MIGRATIONS_DB = "migrations_check"


@pytest.fixture
async def migrations_engine(engine: AsyncEngine) -> AsyncIterator[AsyncEngine]:
    """Empty database, since the shared one is built with create_all and would hide drift."""
    async with engine.connect() as conn:
        conn = await conn.execution_options(isolation_level="AUTOCOMMIT")
        await conn.execute(text(f"DROP DATABASE IF EXISTS {MIGRATIONS_DB}"))
        await conn.execute(text(f"CREATE DATABASE {MIGRATIONS_DB}"))
    clean = get_engine(pool_size=0, database=MIGRATIONS_DB)
    yield clean
    await clean.dispose()
    async with engine.connect() as conn:
        conn = await conn.execution_options(isolation_level="AUTOCOMMIT")
        await conn.execute(text(f"DROP DATABASE {MIGRATIONS_DB} WITH (FORCE)"))


def _config(conn: Connection) -> Config:
    cfg = Config(str(ALEMBIC_INI))
    # env.py runs on this connection instead of building an engine and calling asyncio.run.
    cfg.attributes["connection"] = conn
    return cfg


async def test_models_match_migrations(migrations_engine: AsyncEngine):
    def run(conn: Connection) -> None:
        cfg = _config(conn)
        command.upgrade(cfg, "head")
        # Raises AutogenerateDiffsDetected if a model change has no migration.
        command.check(cfg)

    async with migrations_engine.connect() as conn:
        await conn.run_sync(run)


async def test_migrations_downgrade_to_base(migrations_engine: AsyncEngine):
    def run(conn: Connection) -> None:
        cfg = _config(conn)
        command.upgrade(cfg, "head")
        command.downgrade(cfg, "base")

    async with migrations_engine.connect() as conn:
        await conn.run_sync(run)
